import type { Level } from "../types";

/**
 * 級ごとの実測データ。
 *
 * 出典は公益社団法人 全国工業高等学校長協会が公開している検定試験の実施結果
 * （第26〜30回）。**数値はすべてその報告書に載っている統計値**で、
 * 出題型の内訳だけは5年分1125設問を自分で数えたもの（.local-corpus/graphic-design）。
 * 第26回は問題ページがスキャン画像なので、macOS の Vision で OCR して取り込んだ。
 */

export interface LevelResult {
  /** 回（27〜30） */
  exam: number;
  /** 年度の表示 */
  year: string;
  examinees: number;
  passed: number;
  /** 報告書に載っている合格率(%) */
  passRate: number;
  /**
   * 合格者÷受験者と、報告書の合格率が合わないときの断り書き。
   * **報告書の値を書き換えずに、食い違いをそのまま見せる**ために持つ。
   */
  note?: string;
}

export interface LevelTypeBreakdown {
  /** 説明文に当てはまる用語を4択から選ぶ設問の数（4年分の合計。各級300設問中） */
  term: number;
  /** 記述の正誤を選ぶ設問の数 */
  statement: number;
  /** そのうち「正しいものを選べ」 */
  correct: number;
  /** そのうち「間違っているものを選べ」 */
  incorrect: number;
}

export interface LevelGuide {
  level: Level;
  label: string;
  /** 想定されている学力の程度（報告書の記載） */
  standard: string;
  /** 試験の形 */
  format: string;
  /** この級の性格を1〜3段落で */
  character: string[];
  /** 5年分の実施結果 */
  results: LevelResult[];
  /** 5年分1125設問を数えた内訳（各級375設問） */
  breakdown: LevelTypeBreakdown;
  /** 学習の順番 */
  plan: string[];
}

const YEARS: Record<number, string> = {
  26: "令和3年度",
  27: "令和4年度",
  28: "令和5年度",
  29: "令和6年度",
  30: "令和7年度",
};

const result = (
  exam: number,
  examinees: number,
  passed: number,
  passRate: number,
  note?: string,
): LevelResult => ({
  exam,
  year: YEARS[exam],
  examinees,
  passed,
  passRate,
  note,
});

/** 合格者÷受験者から出した合格率(%)。小数第1位まで。 */
export function computedPassRate(row: LevelResult): number {
  return Math.round((row.passed / row.examinees) * 1000) / 10;
}

